'use strict';
const R = require('./rv_common');
const fs = require('fs');
const OUTD = process.env.SHOTS || require('path').join(require('os').tmpdir(), 'b0dy-rv-shots');
const { vn } = R.H;
(async () => {
  await R.start();
  const t = R.H.backend(vn('2026-10-18', '20:15'));
  const page = await R.open2(t, R.DESK, 'exp');
  await R.login(page, 'duc nam', '0001', true);
  await page.waitForSelector('.pg-book');
  for (const [d, h] of [['2026-10-19', 18], ['2026-10-21', 18], ['2026-10-23', 19]]) await R.cell(page, d, h);
  await R.tap(page, '#cta'); await page.waitForSelector('.pg-tk'); await R.sleep(500);
  t.clock.now = vn('2026-10-20', '09:00'); await page.reload(); await page.waitForSelector(R.vis('[data-a="gochg"]')); await R.sleep(500);
  await R.tap(page, '[data-a="gochg"]'); await page.waitForSelector('.pg-chg');
  await R.cell(page, '2026-10-21', 18); await R.cell(page, '2026-10-22', 19);
  await R.tap(page, '#cta'); await page.waitForSelector('.pg-tk'); await R.sleep(800);
  const [dl] = await Promise.all([page.waitForEvent('download'), R.tap(page, '[data-a="ics"]')]);
  const p = await dl.path(); const ics = fs.readFileSync(p, 'utf8');
  fs.mkdirSync(OUTD, { recursive: true }); fs.writeFileSync(OUTD + '/ticket.ics', ics);
  const lines = ics.split('\r\n');
  const bad = lines.filter(l => Buffer.byteLength(l, 'utf8') > 75);
  R.info('ics name', dl.suggestedFilename());
  R.ok('ics: all lines <= 75 octets, CRLF', bad.length === 0 && !/[^\r]\n/.test(ics), bad);
  const ev = ics.split('BEGIN:VEVENT').slice(1).map(b => ({ uid: (b.match(/UID:([^\r]+)/) || [])[1], st: (b.match(/STATUS:([^\r]+)/) || [])[1], ds: (b.match(/DTSTART:([^\r]+)/) || [])[1] }));
  R.info('ics events', ev);
  R.ok('ics: moved-from slot is CANCELLED, new slot CONFIRMED', ev.some(e => e.st === 'CANCELLED' && /2026-10-21-18/.test(e.uid)) && ev.some(e => e.st === 'CONFIRMED' && /2026-10-22-19/.test(e.uid)), ev);
  const [dl2] = await Promise.all([page.waitForEvent('download'), R.tap(page, '[data-a="png"]')]);
  const png = fs.readFileSync(await dl2.path());
  R.info('png', { name: dl2.suggestedFilename(), bytes: png.length, w: png.readUInt32BE(16), h: png.readUInt32BE(20) });
  fs.writeFileSync(OUTD + '/ticket.png', png);
  await page._ctx.close();
  await R.stop();
})().catch(e => { console.error(e); process.exit(2); });
